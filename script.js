let currentLanguage = "en";

let lastMessageIndex = -1;


const languageBox =
  document.getElementById("languageBox");

const languageButtons =
  document.querySelectorAll(".languageBtn");

const revealBtn =
  document.getElementById("revealBtn");

const loading =
  document.getElementById("loading");

const loadingText =
  document.getElementById("loadingText");

const messageBox =
  document.getElementById("messageBox");

const messageElement =
  document.getElementById("message");

const againBtn =
  document.getElementById("againBtn");

const shareBtn =
  document.getElementById("shareBtn");

const title =
  document.getElementById("title");

const subtitle =
  document.getElementById("subtitle");

const chooseLanguage =
  document.getElementById("chooseLanguage");

const smallText =
  document.getElementById("smallText");

const monthElement =
  document.getElementById("month");


function selectLanguage(language) {

  currentLanguage = language;

  const t =
    translations[language];

  document.documentElement.lang =
    language;

  title.innerHTML =
    t.title;

  subtitle.textContent =
    t.subtitle;

  chooseLanguage.textContent =
    t.choose;

  revealBtn.textContent =
    t.reveal;

  loadingText.textContent =
    t.loading;

  againBtn.textContent =
    t.another;

  shareBtn.textContent =
    t.share;

  smallText.textContent =
    t.small;

  languageBox.classList.add("hidden");

  revealBtn.classList.remove("hidden");

  setTimeout(() => {

    revealMessage();

  }, 700);

}


function getRandomMessage() {

  const list =
    translations[currentLanguage].messages;

  let randomIndex;

  do {

    randomIndex =
      Math.floor(
        Math.random() * list.length
      );

  } while (
    randomIndex === lastMessageIndex &&
    list.length > 1
  );

  lastMessageIndex =
    randomIndex;

  return list[randomIndex];

}


function revealMessage() {

  revealBtn.classList.add("hidden");

  messageBox.classList.add("hidden");

  loading.classList.remove("hidden");

  setTimeout(() => {

    const message =
      getRandomMessage();

    messageElement.textContent =
      `"${message}"`;

    const now =
      new Date();

    const month =
      now.toLocaleString(
        currentLanguage === "zh"
          ? "zh-CN"
          : currentLanguage === "ru"
          ? "ru-RU"
          : currentLanguage === "es"
          ? "es-ES"
          : "en-US",
        {
          month: "long"
        }
      );

    monthElement.textContent =
      `${translations[currentLanguage].month} ${month.toUpperCase()}`;

    loading.classList.add("hidden");

    messageBox.classList.remove("hidden");

  }, 2500);

}


languageButtons.forEach(button => {

  button.addEventListener(
    "click",
    () => {

      const language =
        button.dataset.language;

      selectLanguage(language);

    }
  );

});


revealBtn.addEventListener(
  "click",
  revealMessage
);


againBtn.addEventListener(
  "click",
  revealMessage
);


shareBtn.addEventListener(
  "click",
  async () => {

    const text =
      messageElement.textContent +
      "\n\n✨ Universe139" +
      "\n\n@universe139";

    if (navigator.share) {

      try {

        await navigator.share({

          title:
            "Message From The Universe",

          text:
            text,

          url:
            window.location.href

        });

      } catch (error) {

        console.log(
          "Share cancelled"
        );

      }

    } else {

      try {

        await navigator.clipboard.writeText(
          text
        );

        alert(
          translations[currentLanguage].copied
        );

      } catch (error) {

        alert(text);

      }

    }

  }
);
